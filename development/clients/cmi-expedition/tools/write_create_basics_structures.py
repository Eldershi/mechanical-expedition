import zipfile

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'evidence/create-basics-20261018'
JAR = ROOT / 'instance/mods/create-1.20.1-6.0.8.jar'
with zipfile.ZipFile(JAR) as archive:
    RESOURCES = archive.namelist()
    LANG = json.loads(archive.read('assets/create/lang/zh_cn.json'))
    BLOCKS = {n.removeprefix('assets/create/blockstates/').removesuffix('.json') for n in archive.namelist() if n.startswith('assets/create/blockstates/') and n.endswith('.json')}


def e(item, title, description, prefixes=(), blocks=None, key=None):
    if ':' not in item:
        item = 'create:' + item
    name = item.split(':')[1]
    auto = (f'block.create.{name}.tooltip', f'item.create.{name}.tooltip')
    keys = [k for k in LANG if any(k.startswith(p) for p in (*prefixes, *auto))]
    row = {'item': item, 'title': title, 'description': description,
           'blocks': blocks if blocks is not None else ([name] if name in BLOCKS else []),
           'sources': [{'path': str(JAR), 'entry': 'assets/create/lang/zh_cn.json', 'keys': keys}]}
    if key:
        row['key'] = key
    for stem in {'andesite_ladder': 'MetalLadderBlock', 'andesite_scaffolding': 'MetalScaffoldingBlock'}.get(name, '').split():
        row['sources'] += [{'path': str(JAR), 'entry': p} for p in RESOURCES if p.endswith('/' + stem + '.class')]
    return row


