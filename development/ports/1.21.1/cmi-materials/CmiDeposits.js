StartupEvents.registry('block', event => {
  const kinds = ['aluminum', 'platinum', 'vanadium', 'oil_shale', 'cheese', 'coal']
  kinds.forEach(kind => {
    event.create(`cmi:${kind}_deposit_block`)
      .hardness(-1)
      .resistance(3600000)
      .soundType(SoundType.DEEPSLATE)
      .noDrops()
      .modelGenerator(model => Cmi.applyModel(model, {parent: `cmi:block/deposits/${kind}`}))
      .tagBlock('create_rns:deposit_blocks')
      .tagBlock('mekanism:cardboard_blacklist')
      .tagBlock('ae2:blacklisted/spatial')
      .tagItem('cmi:deposit_blocks')
  })

  event.create('cmi:nether_vanadium_ore').soundType(SoundType.NETHERRACK)
    .hardness(3).resistance(3).requiresTool()
    .modelGenerator(model => Cmi.applyModel(model, {parent: 'cmi:block/deposits/vanadium_ore'}))
    .tagBlock('minecraft:mineable/pickaxe')
    .tagBlock('minecraft:needs_iron_tool')
    .tagBoth('c:ores').tagBoth('c:ores/vanadium')
  event.create('cmi:moon_platinum_ore').soundType(SoundType.STONE)
    .hardness(3).resistance(3).requiresTool()
    .modelGenerator(model => Cmi.applyModel(model, {parent: 'cmi:block/deposits/platinum_ore'}))
    .tagBlock('minecraft:mineable/pickaxe')
    .tagBlock('minecraft:needs_iron_tool')
    .tagBoth('c:ores').tagBoth('c:ores/platinum')
  event.create('cmi:oil_shale').soundType(SoundType.STONE)
    .hardness(3).resistance(3).requiresTool()
    .texture('cmi:block/oil_shale')
    .tagBlock('minecraft:mineable/pickaxe')
})
