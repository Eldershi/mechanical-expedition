ServerEvents.recipes(event => {
  const prefix = 'expedition_industry:'
  const space = 'expedition_space:'
  const fluid = (id, amount) => Fluid.of(id, amount)
  const molten = (metal, units) => fluid('modernfoundry:molten_' + metal, units * 90)
  const recipes = event.recipes.expedition_industry
  const add = (machine, name, ticks, power) => recipes[machine]().duration(ticks)
    .inputFE(power).id(prefix + machine + '/' + name)

  const alloy = (name, input, metal, units) => add('alloy_furnace', name, 120, 3600)
    .inputItems(input).outputFluids(molten(metal, units))
  alloy('copper', '4x minecraft:raw_copper', 'copper', 4)
  alloy('iron', '4x minecraft:raw_iron', 'iron', 4)
  add('alloy_furnace', 'brass', 140, 4200)
    .inputFluids(molten('copper', 2), molten('zinc', 2)).outputFluids(molten('brass', 4))

  const press = (name) => add('hydropress', name, 100, 2400)
  press('brass_plate').inputItems('create:brass_block').outputItems('9x create:brass_sheet')
  press('iron_plate').inputItems('minecraft:iron_block').outputItems('9x create:iron_sheet')
  press('copper_ingot').inputFluids(molten('copper', 4)).outputItems('4x minecraft:copper_ingot')
  press('iron_ingot').inputFluids(molten('iron', 4)).outputItems('4x minecraft:iron_ingot')
  press('steel_ingot').inputFluids(molten('steel', 4)).outputItems('4x ad_astra:steel_ingot')

  const crusher = (name) => add('huge_crusher', name, 100, 2400).inputFluids(fluid('minecraft:water', 1000))
  crusher('cobblestone').inputItems('16x minecraft:cobblestone').outputItems('16x minecraft:gravel')
  crusher('gravel').inputItems('16x minecraft:gravel')
    .outputItems('16x minecraft:sand', '2x minecraft:flint', '2x minecraft:clay_ball')
  crusher('coal').inputItems('8x minecraft:coal')
    .outputItems('4x ' + prefix + 'graphite_dust', '4x minecraft:coal')
  crusher('iron').inputItems('8x minecraft:raw_iron').outputItems('8x create:crushed_raw_iron')

  const blast = (name) => add('blasting_compressor', name, 120, 4800).inputItems('minecraft:tnt')
  blast('brass').inputItems('9x create:brass_block').outputItems('64x create:brass_sheet', '17x create:brass_sheet')
  blast('iron').inputItems('9x minecraft:iron_block').outputItems('64x create:iron_sheet', '17x create:iron_sheet')
  blast('coal').inputItems('16x minecraft:coal_block').outputItems('minecraft:diamond')

  add('shaft_furnace', 'steel_bloom', 180, 7200)
    .inputItems('4x minecraft:coal').inputFluids(fluid('cmi:molten_industrial_iron', 360), fluid('mekanism:oxygen', 200))
    .outputItems('4x ' + prefix + 'semi_finished_steel')
  add('shaft_furnace', 'steel_refining', 140, 6400)
    .inputItems('4x ' + prefix + 'semi_finished_steel', prefix + 'aluminum_slag').outputFluids(molten('steel', 4))

  add('condenser', 'overworld_air', 120, 4800).dimension('minecraft:overworld')
    .inputItems(prefix + 'coolant').outputFluids(fluid(prefix + 'liquid_air', 1000))
  add('condenser', 'lunar_acid', 180, 7200).dimension('ad_astra:moon')
    .inputItems(prefix + 'coolant').outputFluids(fluid('mekanism:hydrogen_chloride', 250))

  add('electrolytic_cell', 'water', 150, 6000).inputFluids(fluid('minecraft:water', 1000))
    .outputFluids(fluid('mekanism:hydrogen', 666), fluid('mekanism:oxygen', 333))
  add('electrolytic_cell', 'brine', 150, 6000)
    .inputItems(space + 'carbon_electrode').inputFluids(fluid('cmi:brine', 1000))
    .outputFluids(fluid('cmi:caustic_soda_solution', 200), fluid('mekanism:chlorine', 400))
  add('electrolytic_cell', 'liquid_air', 160, 6400).inputFluids(fluid(prefix + 'liquid_air', 1000))
    .outputFluids(fluid('mekanism:oxygen', 210), fluid('cmi:liquid_nitrogen', 780))
  add('electrolytic_cell', 'aluminum', 180, 8000)
    .inputItems('2x ' + space + 'carbon_electrode').inputFluids(molten('aluminum', 4))
    .outputItems('2x ' + prefix + 'aluminum_slag').outputFluids(molten('aluminum', 3))

  add('infinity_fetching_pool', 'water', 100, 4000)
    .inputFluids(fluid('minecraft:water', 250)).outputFluids(fluid('minecraft:water', 1000))
  add('infinity_fetching_pool', 'lava', 150, 6000)
    .inputFluids(fluid('minecraft:lava', 500)).outputFluids(fluid('minecraft:lava', 1000))
  add('infinity_fetching_pool', 'brine', 120, 4800)
    .inputFluids(fluid('cmi:brine', 500)).outputFluids(fluid('cmi:brine', 1000))

  add('electro_hydro_resonant_tower', 'electro_hydro', 180, 24000).dimension('ad_astra:moon')
    .inputItems(space + 'carbon_electrode').inputFluids(fluid('mekanism:oxygen', 400), fluid('mekanism:hydrogen', 600))
    .outputFluids(fluid(prefix + 'electro_hydro_fluid', 1000))
  add('electro_hydro_resonant_tower', 'capacitor', 160, 15000)
    .inputItems(space + 'light_composite_plate', 'ad_astra:etrionic_capacitor')
    .inputFluids(fluid(prefix + 'electro_hydro_fluid', 250)).outputItems('4x ' + space + 'electro_hydro_capacitor')
  add('electro_hydro_resonant_tower', 'graphene', 120, 12000)
    .inputItems('4x ' + prefix + 'graphite_dust').inputFluids(fluid(prefix + 'electro_hydro_fluid', 250))
    .outputItems('2x cmi:graphene')

  add('electron_tube_computer', 'compute', 100, 1600).outputItems(prefix + 'data_kib')
  add('electron_tube_computer', 'write_disk', 120, 4800)
    .inputItems('4x ' + prefix + 'data_kib', '#c:ingots/tin', 'create:cogwheel').outputItems(space + 'tin_hard_disk')
  add('large_difference_engine', 'compute', 120, 9600).outputItems(prefix + 'data_mib')
  add('large_difference_engine', 'compress_data', 100, 4000)
    .inputItems('8x ' + prefix + 'data_kib').outputItems('2x ' + prefix + 'data_mib')
  add('large_difference_engine', 'write_disk', 120, 4800)
    .inputItems('4x ' + prefix + 'data_mib', 'create:brass_sheet', 'create:cogwheel').outputItems(space + 'brass_hard_disk')

  const trade = (name) => add('trading_station', name, 100, 2400)
  trade('sell_copper').inputItems('minecraft:copper_block').outputItems('2x ' + prefix + 'trade_credit')
  trade('sell_brass').inputItems('create:brass_block').outputItems('4x ' + prefix + 'trade_credit')
  trade('buy_tin').inputItems('3x ' + prefix + 'trade_credit', 'minecraft:paper').outputItems('4x alltheores:tin_ingot')
  trade('buy_coolant').inputItems('3x ' + prefix + 'trade_credit', 'minecraft:glass_bottle')
    .outputItems('2x ' + prefix + 'coolant')
})
